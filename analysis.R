# -----------------------------------------------------------------------------
# Run from the repository root:   Rscript analysis.R
# Writes tables to results/ and figures to figures/.

suppressPackageStartupMessages({
  library(survival)
  library(ggplot2)
  library(patchwork)
  library(knitr)
})

source("R/functions.R")
dir.create("figures", showWarnings = FALSE)
dir.create("results", showWarnings = FALSE)

data(pbc, package = "survival")
pbc <- prepare_pbc(pbc)
trial <- subset(pbc, randomised)          # 312 patients in the RCT
extra <- subset(pbc, !randomised)         # 106 eligible, non-randomised patients

pal <- c("D-penicillamine" = "#1f6feb", "Placebo" = "#cf222e")
theme_clin <- theme_minimal(base_size = 11) +
  theme(panel.grid.minor = element_blank(), legend.position = "top",
        plot.title = element_text(face = "bold"))

md <- character()   # accumulates the results report
add <- function(...) md <<- c(md, ...)
add("# Results", "",
    sprintf("Generated by `analysis.R` with R %s and survival %s.", getRversion(), packageVersion("survival")), "")

# ---- 1. Baseline characteristics of the randomised trial --------------------
med_iqr <- function(x) {
  q <- quantile(x, c(.25, .5, .75), na.rm = TRUE)
  sprintf("%.1f (%.1f–%.1f)", q[2], q[1], q[3])
}
n_pct <- function(x) sprintf("%d (%.0f%%)", sum(x, na.rm = TRUE), 100 * mean(x, na.rm = TRUE))
t1_rows <- function(d) c(
  "Age, years"                  = med_iqr(d$age),
  "Female"                      = n_pct(d$sex == "Female"),
  "Bilirubin, mg/dL"            = med_iqr(d$bili),
  "Albumin, g/dL"               = med_iqr(d$albumin),
  "Prothrombin time, s"         = med_iqr(d$protime),
  "Any oedema"                  = n_pct(d$edema > 0),
  "Ascites"                     = n_pct(d$ascites == 1),
  "Histologic stage 4 (cirrhosis)" = n_pct(d$stage == 4)
)
t1 <- sapply(split(trial, trial$treatment), t1_rows)
colnames(t1) <- sprintf("%s (n=%d)", colnames(t1), table(trial$treatment))
write.csv(t1, "results/table1.csv")
add("## Table 1. Baseline characteristics (randomised trial)", "",
    kable(t1, format = "pipe"), "")

# ---- 2. Did D-penicillamine improve survival? --------------------------------
km_trt <- survfit(Surv(years, death) ~ treatment, data = trial)
lr <- survdiff(Surv(years, death) ~ treatment, data = trial)
lr_p <- pchisq(lr$chisq, df = 1, lower.tail = FALSE)
cox_trt <- coxph(Surv(years, death) ~ relevel(treatment, "Placebo"), data = trial)
hr_trt <- summary(cox_trt)$conf.int
med_surv <- summary(km_trt)$table[, "median"]

add("## Treatment effect (intention-to-treat)", "",
    sprintf("* Median survival: D-penicillamine %.1f years, placebo %.1f years.",
            med_surv[1], med_surv[2]),
    sprintf("* Log-rank p = %s.", fmt_p(lr_p)),
    sprintf("* Cox HR for death, D-penicillamine vs placebo: %s.",
            fmt_hr(hr_trt[1], hr_trt[3], hr_trt[4])), "")

km_df <- km_to_df(km_trt)
p_km <- ggplot(km_df, aes(time, surv, colour = strata, fill = strata)) +
  geom_rect(data = step_band(km_df), aes(xmin = xmin, xmax = xmax, ymin = lower, ymax = upper),
            inherit.aes = FALSE, fill = pal[step_band(km_df)$strata], alpha = 0.12) +
  geom_step(linewidth = 0.9) +
  geom_point(data = subset(km_df, n.censor > 0), shape = 3, size = 1.5) +
  scale_colour_manual(values = pal, name = NULL) + scale_fill_manual(values = pal, name = NULL) +
  scale_y_continuous(labels = scales::percent, limits = c(0, 1)) +
  scale_x_continuous(breaks = seq(0, 12, 2)) + coord_cartesian(xlim = c(0, 12.5)) +
  annotate("text", x = 0.3, y = 0.08, hjust = 0, size = 3.5,
           label = sprintf("HR %s\nLog-rank p = %s",
                           fmt_hr(hr_trt[1], hr_trt[3], hr_trt[4]), fmt_p(lr_p))) +
  labs(x = "Years since randomisation", y = "Overall survival",
       title = "D-penicillamine vs placebo in PBC") +
  theme_clin
rt <- risk_table(km_trt, seq(0, 12, 2))
p_rt <- ggplot(rt, aes(time, strata, label = n.risk, colour = strata)) +
  geom_text(size = 3.3) +
  scale_colour_manual(values = pal, guide = "none") +
  scale_x_continuous(breaks = seq(0, 12, 2), limits = c(0, 12.5)) +
  labs(x = NULL, y = NULL, subtitle = "Number at risk") +
  theme_void(base_size = 10) + theme(axis.text.y = element_text(hjust = 1),
                                      plot.subtitle = element_text(face = "bold"))
ggsave("figures/km_treatment.png", p_km / p_rt + plot_layout(heights = c(5, 1)),
       width = 7, height = 5.5, dpi = 150, bg = "white")

# ---- 3. Competing risks: death vs liver transplantation ----------------------
cif <- survfit(Surv(years, event) ~ 1, data = pbc)  # Aalen-Johansen estimator
cif_df <- data.frame(time = rep(cif$time, 2),
                     prob = c(cif$pstate[, cif$states == "transplant"], cif$pstate[, cif$states == "death"]),
                     state = rep(c("Liver transplant", "Death (without transplant)"),
                                 each = length(cif$time)))
cif_df <- rbind(data.frame(time = 0, prob = 0, state = unique(cif_df$state)), cif_df)
at10 <- summary(cif, times = 10)$pstate
add("## Competing risks (all 418 patients)", "",
    sprintf("* 10-year cumulative incidence of death without transplant: %.1f%%; of transplant: %.1f%%.",
            100 * at10[, which(cif$states == "death")], 100 * at10[, which(cif$states == "transplant")]),
    "* Treating transplant as simple censoring and reading 1 − KM would overstate mortality; the",
    "  Aalen–Johansen estimator accounts for the competing event.", "")

p_cif <- ggplot(cif_df, aes(time, prob, colour = state)) +
  geom_step(linewidth = 0.9) +
  scale_colour_manual(values = c("Death (without transplant)" = "#cf222e", "Liver transplant" = "#2da44e"),
                      name = NULL) +
  scale_y_continuous(labels = scales::percent, limits = c(0, 0.7)) +
  scale_x_continuous(breaks = seq(0, 12, 2)) + coord_cartesian(xlim = c(0, 12.5)) +
  labs(x = "Years since enrolment", y = "Cumulative incidence",
       title = "Competing risks: death vs liver transplant") +
  theme_clin
ggsave("figures/competing_risks.png", p_cif, width = 7, height = 4.5, dpi = 150, bg = "white")

# ---- 4. Re-deriving the Mayo risk model --------------------------------------
# Fit the Mayo model's five covariates on the randomised cohort (as Dickson et al. did),
# compare with the published coefficients, and check proportional hazards.
mayo_fit <- coxph(Surv(years, death) ~ age + log(bili) + log(albumin) + log(protime) + edema,
                  data = trial)
published <- c(age = 0.039, "log(bili)" = 0.871, "log(albumin)" = -2.53,
               "log(protime)" = 2.38, edema = 0.859)
s <- summary(mayo_fit)
coef_tab <- data.frame(
  Covariate = c("Age (per year)", "log bilirubin", "log albumin", "log prothrombin time",
                "Oedema (0 / 0.5 / 1)"),
  `Published coef.` = sprintf("%.3f", published),
  `Re-estimated coef.` = sprintf("%.3f", coef(mayo_fit)),
  `HR (95% CI) per model unit` = fmt_hr(s$conf.int[, 1], s$conf.int[, 3], s$conf.int[, 4]),
  p = fmt_p(s$coefficients[, "Pr(>|z|)"]),
  check.names = FALSE
)
# Hazard ratios for clinically meaningful contrasts (log-scale terms re-expressed).
contrast <- data.frame(
  term  = c("age", "log(bili)", "log(albumin)", "log(protime)", "edema"),
  label = c("Age: +10 years", "Bilirubin: doubling", "Albumin: 10% lower",
            "Prothrombin time: 10% longer", "Oedema despite diuretics vs none"),
  mult  = c(10, log(2), log(0.9), log(1.1), 1)
)
ci <- confint(mayo_fit)[contrast$term, ]
contrast$hr <- exp(coef(mayo_fit)[contrast$term] * contrast$mult)
lims <- cbind(exp(ci[, 1] * contrast$mult), exp(ci[, 2] * contrast$mult))
contrast$lo <- apply(lims, 1, min)
contrast$hi <- apply(lims, 1, max)
coef_tab$`HR (95% CI) for clinical contrast` <- paste0(contrast$label, ": ",
                                                      fmt_hr(contrast$hr, contrast$lo, contrast$hi))
zph <- cox.zph(mayo_fit)
write.csv(coef_tab, "results/mayo_model.csv", row.names = FALSE)
add("## Mayo risk model re-estimated on the randomised cohort", "",
    kable(coef_tab, format = "pipe", row.names = FALSE), "",
    sprintf("* Harrell's C-index (apparent): %.3f.", mayo_fit$concordance["concordance"]),
    sprintf("* Proportional-hazards test (Schoenfeld residuals), global p = %s.",
            fmt_p(zph$table["GLOBAL", "p"])), "")

zph_df <- do.call(rbind, lapply(seq_len(ncol(zph$y)), function(j)
  data.frame(time = zph$x, resid = zph$y[, j], term = colnames(zph$y)[j])))
zph_p <- setNames(fmt_p(zph$table[-nrow(zph$table), "p"]), colnames(zph$y))
zph_df$term <- factor(zph_df$term, levels = colnames(zph$y),
                      labels = sprintf("%s (p = %s)", colnames(zph$y), zph_p))
p_zph <- ggplot(zph_df, aes(time, resid)) +
  geom_point(alpha = 0.35, size = 1) +
  geom_smooth(method = "loess", formula = y ~ x, se = TRUE, colour = "#1f6feb") +
  geom_hline(yintercept = 0, linetype = 2, colour = "grey50") +
  facet_wrap(~term, scales = "free_y", ncol = 3) +
  labs(x = "Transformed time (KM scale)", y = "Scaled Schoenfeld residual",
       title = "Checking proportional hazards") +
  theme_clin
ggsave("figures/schoenfeld_residuals.png", p_zph, width = 9, height = 5.5, dpi = 150, bg = "white")

# ---- 5. External check: published Mayo score in the 106 non-randomised patients
extra$mayo <- with(extra, mayo_risk_score(age, bili, albumin, protime, edema))
extra_cc <- subset(extra, !is.na(mayo))
c_extra <- concordance(Surv(years, death) ~ mayo, data = extra_cc, reverse = TRUE)
add("## Validation of the published score in non-randomised patients", "",
    sprintf("* n = %d patients not used to fit the model. C-index of the *published* Mayo score: %.3f (95%% CI %.3f–%.3f).",
            nrow(extra_cc), c_extra$concordance,
            c_extra$concordance - 1.96 * sqrt(c_extra$var),
            c_extra$concordance + 1.96 * sqrt(c_extra$var)), "")

# ---- 6. Risk stratification across the whole cohort --------------------------
pbc$mayo <- with(pbc, mayo_risk_score(age, bili, albumin, protime, edema))
pbc_cc <- subset(pbc, !is.na(mayo))
cuts <- quantile(pbc_cc$mayo, c(1/3, 2/3))
pbc_cc$risk_group <- cut(pbc_cc$mayo, c(-Inf, cuts, Inf),
                         labels = c("Low", "Intermediate", "High"))
km_risk <- survfit(Surv(years, death) ~ risk_group, data = pbc_cc)
surv5 <- summary(km_risk, times = 5)
add("## Survival by Mayo risk tertile (all patients)", "",
    kable(data.frame(`Risk group` = sub("^.*=", "", surv5$strata),
                     `5-year survival` = sprintf("%.0f%% (%.0f–%.0f%%)",
                                                 100 * surv5$surv, 100 * surv5$lower, 100 * surv5$upper),
                     check.names = FALSE), format = "pipe"), "")

risk_pal <- c(Low = "#2da44e", Intermediate = "#bf8700", High = "#cf222e")
p_risk <- ggplot(km_to_df(km_risk), aes(time, surv, colour = factor(strata, names(risk_pal)))) +
  geom_step(linewidth = 0.9) +
  scale_colour_manual(values = risk_pal, name = "Mayo risk score tertile") +
  scale_y_continuous(labels = scales::percent, limits = c(0, 1)) +
  scale_x_continuous(breaks = seq(0, 12, 2)) + coord_cartesian(xlim = c(0, 12.5)) +
  labs(x = "Years since enrolment", y = "Overall survival",
       title = "Prognostic separation by the Mayo risk score") +
  theme_clin
ggsave("figures/km_mayo_risk.png", p_risk, width = 7, height = 4.5, dpi = 150, bg = "white")

