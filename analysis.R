p_forest <- ggplot(forest, aes(hr, term)) +
  geom_vline(xintercept = 1, linetype = 2, colour = "grey50") +
  geom_errorbarh(aes(xmin = lo, xmax = hi), height = 0.2, colour = "#1f6feb") +
  geom_point(size = 2.5, colour = "#1f6feb") +
  geom_text(aes(label = sprintf("%.2f", hr)), vjust = -1, size = 3.2, colour = "grey20") +
  scale_x_log10(breaks = c(0.5, 1, 1.5, 2, 3, 4)) +
  labs(x = "Hazard ratio for death (log scale, 95% CI)", y = NULL,
       title = "Multivariable Cox model (Mayo covariates)",
       subtitle = "Each hazard ratio is mutually adjusted") +
  theme_clin
ggsave("figures/forest_plot.png", p_forest, width = 7, height = 3.8, dpi = 150, bg = "white")

